#!/usr/bin/env python3
"""Generate tests/unit/core/rng_kat.inc, the known-answer vectors of the RNG (A04).

The vectors come from the bit-exact Python reference rng_reference.py. The C++ tests compare
the library against them on every CI runner, which proves the draws are identical on all
platforms (plan section 9.1, A04). The output is deterministic, so CI can regenerate it and
fail on any difference to the committed file.

Usage:
    python tools/rng/gen_rng_kat.py           # regenerate the file
    python tools/rng/gen_rng_kat.py --check   # exit 1 if the file is out of date

Exit codes: 0 success, 1 file out of date (--check), 2 I/O error.
"""

import argparse
import difflib
import sys
from pathlib import Path
from typing import Iterable, List, Optional

import rng_reference as r

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO_ROOT / "tests" / "unit" / "core" / "rng_kat.inc"

# Inputs of the vectors. Changing them only changes the test data, not the library.
MIX64_INPUTS = [0, 1, 2, r.GOLDEN_GAMMA, r.MASK64, 0x0123456789ABCDEF, 1 << 63]
COMBINE_INPUTS = [(0, 0), (0, 1), (1, 0), (r.MASK64, r.MASK64), (0x0123456789ABCDEF, 66049)]
HASH_ID_INPUTS = ["", "a", "wg", "c01_allocate", "p01_tectonics", "test.normal"]
STAGE_KEY_INPUTS = [(0, "c01_allocate", 0), (12345, "c02_seed", 1),
                    (r.MASK64, "p04_erosion", 7), (20261021, "c06_erosion_rivers", 31)]
KEYS = [r.stage_key(0, "c01_allocate", 0), r.stage_key(42, "c06_erosion_rivers", 3), r.MASK64]
CELLS = [0, 1, 256, 66049, 1 << 40]
DRAWS = [0, 1, 7]
INDEX_SIZES = [1, 2, 5, 257, 1 << 40]
EXP_FIXED = [0.0, -0.0, 1.0, -1.0, 0.5, -0.5, 0.3, 1e-30, 2.0 ** -28, -(2.0 ** -29),
             0.34657359027997264, 0.3465735902799727, 1.0397207708399179, 1.03972077083992,
             2.0, 10.0, -10.0, 100.0, 700.0, 709.0, 709.782712893384, 709.79, -708.0,
             -720.0, -745.0, -745.2, 1000.0, -1000.0, r.from_bits(0x7FF0000000000000),
             r.from_bits(0xFFF0000000000000)]
LOG_FIXED = [1.0, 2.0, 0.5, 2.718281828459045, 10.0, 1.5, 0.75, 3.0, 1.0 + 2.0 ** -30,
             1.0 - 2.0 ** -30, 1.0 + 2.0 ** -52, 1e-300, 1e-310, 5e-324,
             1.7976931348623157e308, 0.0, -0.0, r.from_bits(0x7FF0000000000000)]
LOG_FACTORIAL_INPUTS = [0, 1, 2, 5, 9, 10, 11, 12, 20, 100, 1000, 10 ** 6, 10 ** 12]
INV_NORMAL_FIXED = [1e-300, 1e-100, 1e-10, 1e-5, 0.001, 0.025, 0.07, 0.075, 0.0751, 0.3, 0.5,
                    0.7, 0.925, 0.975, 0.999, 1.0 - 1e-10, 1.0 - 2.0 ** -53, 0.0, 1.0]
NORMAL_PARAMS = [(0.0, 1.0), (10.0, 2.5), (-3.0, 0.1)]
POISSON_LAMBDAS = [0.0, 1e-3, 0.5, 4.0, 9.99, 10.0, 30.0, 1000.0, 1e6, 1e12]
POISSON_VALUES = 8
WEIGHT_SETS = [[1.0, 2.0, 3.0, 4.0, 10.0], [0.0, 1.0, 0.0, 2.0, 0.0], [0.25]]
WEIGHT_US = [0.0, 0.05, 0.1, 0.1499999, 0.15, 0.5, 0.95, 1.0 - 2.0 ** -53]
RANDOM_COUNT = 24


def _random_inputs(name: str, lo: float, hi: float) -> List[float]:
    key = r.stage_key(0, "kat." + name, 0)
    return [r.uniform(key, i, 0, lo, hi) for i in range(RANDOM_COUNT)]


def _hex(v: int) -> str:
    return "0x{:016X}".format(v)


def _bits(x: float) -> str:
    return _hex(r.to_bits(x))


def _table(type_name: str, name: str, rows: List[str]) -> List[str]:
    out = ["inline constexpr std::array<{}, {}> {}{{{{".format(type_name, len(rows), name)]
    out += ["    {{{}}},".format(row) for row in rows]
    out += ["}};", ""]
    return out


def _str(text: str) -> str:
    return '"' + text + '"'  # identifiers are plain ASCII


def render() -> str:
    exp_inputs = EXP_FIXED + _random_inputs("exp", -740.0, 709.0)
    log_inputs = LOG_FIXED + [r.det_exp(x) for x in _random_inputs("log", -740.0, 709.0)]
    inv_inputs = INV_NORMAL_FIXED + _random_inputs("inverse_normal_cdf", 0.0, 1.0)

    lines = [
        "// Known-answer vectors of the RNG (A04). Generated by tools/rng/gen_rng_kat.py from the",
        "// bit-exact Python reference tools/rng/rng_reference.py; do not edit. Doubles are IEEE",
        "// bit patterns.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace wg::test::kat {",
        "",
        "struct Mix64 { std::uint64_t in; std::uint64_t out; };",
        "struct Combine { std::uint64_t h; std::uint64_t w; std::uint64_t out; };",
        "struct HashId { std::string_view text; std::uint64_t out; };",
        "struct StageKey { std::uint64_t seed; std::string_view id; std::uint32_t attempt; "
        "std::uint64_t out; };",
        "struct Draw { std::uint64_t key; std::uint64_t cell; std::uint64_t draw; "
        "std::uint64_t bits; std::uint64_t unit01; std::uint64_t open01; };",
        "struct UniformIndex { std::uint64_t key; std::uint64_t cell; std::uint64_t draw; "
        "std::uint64_t n; std::uint64_t out; };",
        "struct Unary { std::uint64_t in; std::uint64_t out; };",
        "struct LogFactorial { std::uint64_t k; std::uint64_t out; };",
        "struct Normal { std::uint64_t key; std::uint64_t cell; std::uint64_t draw; "
        "std::uint64_t mean; std::uint64_t sd; std::uint64_t normal; std::uint64_t log_normal; };",
        "struct Poisson { std::uint64_t key; std::uint64_t id; std::uint64_t lambda; "
        + "std::array<std::uint64_t, {}> values; std::uint64_t draws; }};".format(POISSON_VALUES),
        "struct WeightSet { std::array<double, 5> weights; std::size_t size; };",
        "struct WeightedSample { std::size_t set; std::uint64_t u; std::size_t bin; };",
        "struct WeightedKeyed { std::size_t set; std::uint64_t key; std::uint64_t cell; "
        "std::uint64_t draw; std::size_t bin; };",
        "",
    ]

    lines += _table("Mix64", "kMix64",
                    ["{}, {}".format(_hex(x), _hex(r.mix64(x))) for x in MIX64_INPUTS])
    lines += _table("Combine", "kCombine", ["{}, {}, {}".format(_hex(h), _hex(w),
                                                                 _hex(r.combine(h, w)))
                                            for h, w in COMBINE_INPUTS])
    lines += _table("HashId", "kHashId", ["{}, {}".format(_str(t), _hex(r.hash_id(t)))
                                          for t in HASH_ID_INPUTS])
    lines += _table("StageKey", "kStageKey",
                    ["{}, {}, {}, {}".format(_hex(s), _str(i), a, _hex(r.stage_key(s, i, a)))
                     for s, i, a in STAGE_KEY_INPUTS])

    draws = []
    for key in KEYS:
        for cell in CELLS:
            for draw in DRAWS:
                b = r.bits64(key, cell, draw)
                draws.append("{}, {}, {}, {}, {}, {}".format(
                    _hex(key), _hex(cell), draw, _hex(b), _bits(r.to_unit01(b)),
                    _bits(r.to_open01(b))))
    lines += _table("Draw", "kDraw", draws)

    lines += _table("UniformIndex", "kUniformIndex", [
        "{}, {}, {}, {}, {}".format(_hex(KEYS[1]), _hex(cell), draw, _hex(n),
                                    _hex(r.uniform_index(KEYS[1], cell, draw, n)))
        for n in INDEX_SIZES for cell in CELLS[:3] for draw in DRAWS[:2]])

    lines += _table("Unary", "kDetExp", ["{}, {}".format(_bits(x), _bits(r.det_exp(x)))
                                         for x in exp_inputs])
    lines += _table("Unary", "kDetLog", ["{}, {}".format(_bits(x), _bits(r.det_log(x)))
                                         for x in log_inputs])
    lines += _table("LogFactorial", "kLogFactorial",
                    ["{}, {}".format(k, _bits(r.log_factorial(k))) for k in LOG_FACTORIAL_INPUTS])
    lines += _table("Unary", "kInverseNormalCdf",
                    ["{}, {}".format(_bits(p), _bits(r.inverse_normal_cdf(p))) for p in inv_inputs])

    normals = []
    for key in KEYS[:2]:
        for cell in CELLS[:3]:
            for draw in DRAWS:
                for mean, sd in NORMAL_PARAMS:
                    normals.append("{}, {}, {}, {}, {}, {}, {}".format(
                        _hex(key), _hex(cell), draw, _bits(mean), _bits(sd),
                        _bits(r.normal(key, cell, draw, mean, sd)),
                        _bits(r.log_normal(key, cell, draw, mean, sd))))
    lines += _table("Normal", "kNormal", normals)

    poissons = []
    for key in KEYS[:2]:
        for stream_id in (0, 66049):
            for lam in POISSON_LAMBDAS:
                s = r.RngStream(key, stream_id)
                values = [r.poisson(s, lam) for _ in range(POISSON_VALUES)]
                poissons.append("{}, {}, {}, {{{}}}, {}".format(
                    _hex(key), stream_id, _bits(lam), ", ".join(str(v) for v in values),
                    s.draw))
    lines += _table("Poisson", "kPoisson", poissons)

    lines += _table("WeightSet", "kWeightSets", [
        "{{{}}}, {}".format(", ".join(repr(w) for w in (ws + [0.0] * (5 - len(ws)))), len(ws))
        for ws in WEIGHT_SETS])
    samples = []
    keyed = []
    for set_index, ws in enumerate(WEIGHT_SETS):
        bins = r.WeightedBins(ws)
        for u in WEIGHT_US:
            samples.append("{}, {}, {}".format(set_index, _bits(u), bins.sample(u)))
        for cell in CELLS:
            for draw in DRAWS:
                keyed.append("{}, {}, {}, {}, {}".format(set_index, _hex(KEYS[0]), _hex(cell),
                                                         draw,
                                                         bins.sample_keyed(KEYS[0], cell, draw)))
    lines += _table("WeightedSample", "kWeightedSample", samples)
    lines += _table("WeightedKeyed", "kWeightedKeyed", keyed)

    lines += ["}  // namespace wg::test::kat", ""]
    return "\n".join(lines)


def main(argv: Optional[Iterable[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true",
                        help="compare with --out instead of writing it; exit 1 on a difference")
    args = parser.parse_args(None if argv is None else list(argv))

    text = render()
    if args.check:
        try:
            current = args.out.read_text(encoding="utf-8")
        except OSError:
            current = ""
        if current != text:
            diff = difflib.unified_diff(current.splitlines(True), text.splitlines(True),
                                        str(args.out), "generated")
            sys.stderr.writelines(diff)
            print("error: {} is out of date; run tools/rng/gen_rng_kat.py".format(args.out),
                  file=sys.stderr)
            return 1
        return 0

    try:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        with args.out.open("w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    except OSError as e:
        print("error: {}".format(e), file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
